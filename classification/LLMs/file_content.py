# GITHUB FETCH
# ==============================

def github_raw_url(blob_url: str) -> str:
    return (
        blob_url
        .replace("github.com", "raw.githubusercontent.com")
        .replace("/blob/", "/")
    )


def extract_satd_line_number(url: str) -> int:
    """This function is used to extract the SATD line number from a GitHub URL (#L123)."""
    match = re.search(r"#L(\d+)", url)
    return int(match.group(1)) if match else None


def fetch_full_file(url: str, token: str = None) -> str:
    raw_url = github_raw_url(url.split("#")[0])
    headers = {}
    if token:
        headers["Authorization"] = f"token {token}"

    response = requests.get(raw_url, headers=headers)
    if response.status_code != 200:
        print(f"❌ Failed to fetch: {url} (HTTP {response.status_code})")
        return ""
    return response.text


